const fn encode(rows: [&str; 10]) -> [u8; 10] {
    let mut glyph = [0; 10];
    let mut row = 0;
    while row < 10 {
        let pixels = rows[row].as_bytes();
        if pixels.len() < 6 {
            panic!("console font row is too short");
        }
        let mut trailing = 8;
        while trailing < pixels.len() {
            if pixels[trailing] != b'.' {
                panic!("console font glyph exceeds its cell width");
            }
            trailing += 1;
        }
        let mut column = 0;
        while column < 8 {
            if column < pixels.len() && pixels[column] == b'#' {
                glyph[row] |= 0x80 >> column;
            }
            column += 1;
        }
        row += 1;
    }
    glyph
}

macro_rules! glyph {
    ($($row:literal),+ $(,)?) => {
        encode([$($row),+])
    };
}

