const fn encode(rows: &str) -> [u8; 10] {
    let mut glyph = [0; 10];
    let bytes = rows.as_bytes();
    let mut row = 0usize;
    let mut column = 0usize;
    let mut index = 0usize;
    while index < bytes.len() {
        match bytes[index] {
            b' ' | b'\t' | b'\r' => {}
            b'\n' => {
                if column != 0 && column != 8 {
                    panic!("console font row must be eight pixels wide");
                }
                if column == 8 {
                    row += 1;
                    column = 0;
                }
            }
            b'.' | b'#' => {
                if row >= 10 || column >= 8 {
                    panic!("console font glyph exceeds its 8x10 cell");
                }
                if bytes[index] == b'#' {
                    glyph[row] |= 0x80 >> column;
                }
                column += 1;
            }
            _ => panic!("console font pixels must be '.' or '#'"),
        }
        index += 1;
    }
    if row != 10 || column != 0 {
        panic!("console font glyph must contain ten rows of eight pixels");
    }
    glyph
}

macro_rules! glyph {
    ($rows:literal) => {
        encode($rows)
    };
}

